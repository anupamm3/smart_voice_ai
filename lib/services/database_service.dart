  // Database statistics
  Future<Map<String, int>> getDatabaseStats() async {
    final notesBox = Hive.box<Note>(_notesBox);
    final remindersBox = Hive.box<Reminder>(_remindersBox);
    final chatBox = Hive.box<ChatHistory>(_chatHistoryBox);
    final faqBox = Hive.box<FAQ>(_faqBox);

    return {
      'notes': notesBox.length,
      'reminders': remindersBox.length,
      'chatHistory': chatBox.length,
      'faqs': faqBox.length,
    };
  }

  // Close all boxes (call this when app is closing)
  Future<void> dispose() async {
    await Hive.close();
  }
}
